"""Upgrades from 0.2.x keep data and settings: deploy/.env is rewritten to CORVEX_* names, the old
Docker volumes are copied into the new ones (only when those are empty, never deleted — the
summary says how to remove them), the database file is renamed with its -wal/-shm only when the
new name doesn't exist yet, and PENTESTIQ_* settings are still read as a silent fallback."""
import os
import sqlite3
import subprocess
import sys
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from pentestiq.storage.paths import DB_NAME, LEGACY_DB_NAME, migrate_db_name

ROOT = Path(__file__).resolve().parents[1]
SH = (ROOT / "install.sh").read_text(encoding="utf-8")
PS1 = (ROOT / "install.ps1").read_text(encoding="utf-8")
# Never reach this machine's Docker, services or sudo from a test, whatever installer function runs.
_GUARD = ('docker(){ echo "docker $*" >> "${CORVEX_TEST_DOCKER_LOG:-/dev/null}"; return 1; }; '
          'systemctl(){ return 1; }; sudo(){ return 1; }; runuser(){ return 1; }; ')

posix = pytest.mark.skipif(sys.platform == "win32", reason="drives install.sh through a POSIX bash")

OLD_ENV = """# Corvex-RedOps deployment secrets — generated by install.sh. Keep private; do not commit.
MOBSF_API_KEY=mk
PENTESTIQ_SECRET_KEY=s3cret
PENTESTIQ_PORT=9090
PENTESTIQ_LISTEN=0.0.0.0
CORVEX_TRUSTED_PROXIES=127.0.0.1,::1
PENTESTIQ_AI=1
OLLAMA_URL=http://ollama:11434
PENTESTIQ_AI_MODEL=qwen2.5:7b-instruct
CORVEX_ADMIN_USER=corvex
CORVEX_ADMIN_PASSWORD=
"""


def _sh(tmp_path, script):
    env = {**os.environ, "CORVEX_INSTALL_SOURCE_ONLY": "1", "NO_COLOR": "1"}
    cmd = f'source "{ROOT}/install.sh"; {_GUARD}SUDO=""; ENV_FILE="{tmp_path}/deploy/.env"; {script}'
    return subprocess.run(["bash", "-c", cmd], capture_output=True, text=True, env=env, timeout=60,
                          encoding="utf-8", errors="replace")


# ---- deploy/.env --------------------------------------------------------------------------
@posix
def test_the_env_file_is_rewritten_to_corvex_names(tmp_path):
    (tmp_path / "deploy").mkdir(); env = tmp_path / "deploy/.env"
    env.write_text(OLD_ENV); env.chmod(0o600)
    r = _sh(tmp_path, "migrate_env_file")
    new = env.read_text()
    assert "PENTESTIQ_" not in new and "Settings renamed to CORVEX_*" in r.stdout
    for line in ("CORVEX_SECRET_KEY=s3cret", "CORVEX_PORT=9090", "CORVEX_LISTEN=0.0.0.0", "CORVEX_AI=1",
                 "CORVEX_AI_MODEL=qwen2.5:7b-instruct", "OLLAMA_URL=http://ai:11434", "MOBSF_API_KEY=mk",
                 "CORVEX_TRUSTED_PROXIES=127.0.0.1,::1", "CORVEX_ADMIN_USER=corvex"):
        assert line in new.splitlines(), line
    assert new.startswith("# Corvex-RedOps deployment secrets")
    assert oct(env.stat().st_mode)[-3:] == "600"
    before = env.read_text(); _sh(tmp_path, "migrate_env_file"); assert env.read_text() == before   # idempotent


@posix
def test_a_value_already_set_under_the_new_name_wins(tmp_path):
    (tmp_path / "deploy").mkdir(); env = tmp_path / "deploy/.env"
    env.write_text("PENTESTIQ_PORT=9090\nCORVEX_PORT=8181\n")
    _sh(tmp_path, "migrate_env_file")
    assert env.read_text().splitlines() == ["CORVEX_PORT=8181"]


@posix
def test_settings_are_read_from_either_name_before_the_rewrite(tmp_path):
    (tmp_path / "deploy").mkdir(); (tmp_path / "deploy/.env").write_text(OLD_ENV)
    r = _sh(tmp_path, 'parse_args; load_existing_settings; echo "PORT=$PORT AI=$(env_get_any AI)"')
    assert "PORT=9090 AI=1" in r.stdout


# ---- Docker volumes -----------------------------------------------------------------------
def _fake_docker(tmp_path):
    """Volumes and containers as directories/files under tmp_path/docker; every call logged."""
    d = tmp_path / "docker"; (d / "volumes").mkdir(parents=True); (d / "containers").mkdir()
    return d, f'''
      D="{d}"; LOG="{tmp_path}/docker.log"
      docker(){{ echo "docker $*" >> "$LOG"
        case "$1 $2" in
          "container inspect") [ -e "$D/containers/$3" ];;
          "rm -f") rm -f "$D/containers/$3";;
          "volume create") mkdir -p "$D/volumes/$3";;
          *) return 0;;
        esac; }}
      volume_exists(){{ [ -d "$D/volumes/$1" ]; }}
      volume_empty(){{ [ -z "$(ls -A "$D/volumes/$1")" ]; }}
      copy_volume(){{ echo "copy $1 -> $2 owner=${{3:-}}" >> "$LOG"; cp -a "$D/volumes/$1/." "$D/volumes/$2/"; }}
    '''


@posix
def test_old_volumes_are_copied_into_empty_new_ones_and_never_deleted(tmp_path):
    d, stub = _fake_docker(tmp_path)
    (d / "volumes/deploy_pentestiq-data").mkdir(); (d / "volumes/deploy_pentestiq-data/pentestiq.db").write_text("DATA")
    (d / "volumes/deploy_ollama-models").mkdir(); (d / "volumes/deploy_ollama-models/model").write_text("M")
    for c in ("pentestiq-api", "pentestiq-mobsf", "pentestiq-ollama"):
        (d / "containers" / c).write_text("")
    r = _sh(tmp_path, stub + 'migrate_legacy_docker; echo "RC=$? MIGRATED=$MIGRATED_VOLUMES"')
    assert "RC=0 MIGRATED=deploy_pentestiq-data deploy_ollama-models" in r.stdout
    assert (d / "volumes/corvex-redops-data/pentestiq.db").read_text() == "DATA"
    assert (d / "volumes/corvex-redops-ai-models/model").read_text() == "M"
    assert (d / "volumes/deploy_pentestiq-data/pentestiq.db").read_text() == "DATA"      # old one kept
    log = (tmp_path / "docker.log").read_text()
    assert "copy deploy_pentestiq-data -> corvex-redops-data owner=10001:10001" in log
    assert "volume rm" not in log and not list((d / "containers").iterdir())            # containers only


@posix
def test_a_new_volume_that_already_has_data_is_left_alone(tmp_path):
    d, stub = _fake_docker(tmp_path)
    (d / "volumes/deploy_pentestiq-data").mkdir(); (d / "volumes/deploy_pentestiq-data/pentestiq.db").write_text("OLD")
    (d / "volumes/corvex-redops-data").mkdir(); (d / "volumes/corvex-redops-data/corvex-redops.db").write_text("NEW")
    r = _sh(tmp_path, stub + 'migrate_legacy_docker; echo "MIGRATED=[$MIGRATED_VOLUMES]"')
    assert "MIGRATED=[]" in r.stdout
    assert sorted(p.name for p in (d / "volumes/corvex-redops-data").iterdir()) == ["corvex-redops.db"]


@posix
def test_the_summary_says_how_to_remove_the_old_volumes(tmp_path):
    r = _sh(tmp_path, 'detect_distro; native_layout; parse_args; ENGINE_USED=docker; '
                      'MIGRATED_VOLUMES="deploy_pentestiq-data deploy_ollama-models"; summary')
    assert "your data was copied from deploy_pentestiq-data deploy_ollama-models (left in place)" in r.stdout
    assert "sudo docker volume rm deploy_pentestiq-data deploy_ollama-models" in r.stdout


def test_the_migration_runs_after_the_build_and_before_the_stack_starts():
    body = SH[SH.index("deploy_docker() {"):SH.index("try_docker() {")]
    assert body.index("compose build") < body.index("migrate_legacy_docker") < body.index("compose up -d")
    assert "docker volume rm" not in SH.replace('sudo docker volume rm %s', '')        # only ever printed


def test_install_ps1_migrates_the_same_way():
    for part in ("function Update-EnvNames", "function Move-LegacyDocker", '"deploy_pentestiq-data", "corvex-redops-data"',
                 "Move-LegacyDocker)", "docker volume rm $($script:MigratedVolumes -join ' ')"):
        assert part in PS1, part
    assert PS1.index("function Write-Env {\n  Update-EnvNames") > 0


# ---- the database file --------------------------------------------------------------------
def _old_db(d: Path):
    """A 0.2.x data dir: pentestiq.db in WAL mode with an account, its -wal/-shm beside it."""
    from pentestiq.auth.service import AuthService
    from pentestiq.storage import SqliteAuthStore
    st = SqliteAuthStore(str(d / LEGACY_DB_NAME))
    AuthService(st, secret_key="s", session_ttl=3600).register("Corvex-RedOps", "corvex", "old-install-pass-1")
    return st


def test_the_database_is_renamed_with_its_wal_and_the_account_still_signs_in(tmp_path, monkeypatch):
    st = _old_db(tmp_path)
    st._conn.close(); st._rconn.close()
    monkeypatch.delenv("CORVEX_ADMIN_PASSWORD", raising=False)
    from pentestiq.api.app import create_app
    from pentestiq.config import AppConfig
    c = TestClient(create_app(config=AppConfig(data_dir=str(tmp_path))))
    assert not (tmp_path / LEGACY_DB_NAME).exists() and (tmp_path / DB_NAME).exists()
    assert c.get("/setup/status").json()["setup_required"] is False               # the old admin counts
    assert c.post("/auth/login", json={"username": "corvex", "password": "old-install-pass-1"}).status_code == 200


def test_the_rename_moves_the_sidecars_and_never_overwrites(tmp_path):
    for s in ("", "-wal", "-shm"):
        (tmp_path / (LEGACY_DB_NAME + s)).write_text("old" + s)
    assert migrate_db_name(tmp_path) is True
    assert sorted(p.name for p in tmp_path.iterdir()) == [DB_NAME, DB_NAME + "-shm", DB_NAME + "-wal"]
    assert (tmp_path / (DB_NAME + "-wal")).read_text() == "old-wal"
    (tmp_path / LEGACY_DB_NAME).write_text("stray")                                  # both present: hands off
    assert migrate_db_name(tmp_path) is False and (tmp_path / DB_NAME).read_text() == "old"


def test_an_open_database_passed_in_is_never_renamed(tmp_path, monkeypatch):
    st = _old_db(tmp_path)
    from pentestiq.api.app import create_app
    from pentestiq.auth.service import AuthService
    from pentestiq.config import AppConfig
    from pentestiq.storage import SqliteEngagementStore
    create_app(store=SqliteEngagementStore(str(tmp_path / LEGACY_DB_NAME)),
               auth=AuthService(st, secret_key="s", session_ttl=3600), config=AppConfig(data_dir=str(tmp_path)))
    assert (tmp_path / LEGACY_DB_NAME).exists() and not (tmp_path / DB_NAME).exists()


# ---- settings and stored identifiers ------------------------------------------------------
def test_old_setting_names_are_a_silent_fallback(monkeypatch):
    from pentestiq.config import AppConfig
    for k in ("CORVEX_SECRET_KEY", "CORVEX_AI", "CORVEX_AI_MODEL", "CORVEX_SCAN_TIMEOUT_S"):
        monkeypatch.delenv(k, raising=False)
    monkeypatch.setenv("PENTESTIQ_SECRET_KEY", "old-key"); monkeypatch.setenv("PENTESTIQ_AI", "1")
    monkeypatch.setenv("PENTESTIQ_SCAN_TIMEOUT_S", "600")
    c = AppConfig()
    assert (c.secret_key, c.ai_enabled, c.scan_timeout_s) == ("old-key", True, 600)
    monkeypatch.setenv("CORVEX_SECRET_KEY", "new-key"); monkeypatch.setenv("CORVEX_AI", "0")
    c = AppConfig()
    assert (c.secret_key, c.ai_enabled) == ("new-key", False)


def test_findings_stored_with_old_engine_ids_keep_their_labels_and_model_features():
    from pentestiq.ai.feedback import featurize
    from pentestiq.models import Asset, Finding
    from pentestiq.models.enums import AssetType
    from pentestiq.reporting.model import engine_label
    assert engine_label("pentestiq-fuzz") == engine_label("corvex-fuzz") != "Automated scanning engine"
    a = Asset(type=AssetType.WEB, identifier="https://x.test")
    assert featurize(Finding(asset=a, title="t", source_tools=["pentestiq-fuzz"])) == \
        featurize(Finding(asset=a, title="t", source_tools=["corvex-fuzz"]))
